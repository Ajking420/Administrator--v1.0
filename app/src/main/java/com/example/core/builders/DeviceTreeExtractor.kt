    suspend fun exportDeviceTreeTarGz(
        context: Context,
        files: List<DeviceTreeFile>,
        simulationMode: Boolean
    ): ExportOutcome = withContext(Dispatchers.IO) {
        val tarBytes = ByteArrayOutputStream().use { tarOut ->
            for (f in files) {
                val unixBytes = f.content.replace("\r\n", "\n").toByteArray(Charsets.UTF_8)
                BootImagePatcher.writeTarEntry(tarOut, "device/samsung/e15x/${f.path}", unixBytes)
            }
            tarOut.write(ByteArray(1024))
            tarOut.toByteArray()
        }
        val gzBytes = ByteArrayOutputStream().use { gzRaw ->
            GZIPOutputStream(gzRaw).use { gz -> gz.write(tarBytes) }
            gzRaw.toByteArray()
        }
        ExportManager.exportBytes(
            context = context,
            subfolder = "DeviceTrees",
            fileName = "f15_device_tree.tar.gz",
            bytes = gzBytes,
            mimeType = "application/gzip",
            simulationMode = simulationMode
        )
    }
}
